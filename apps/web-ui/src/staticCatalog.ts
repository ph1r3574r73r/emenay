export function mergeCatalog(live: ModuleInfo[]): ModuleInfo[] {
  const byId = new Map<string, ModuleInfo>()
  for (const m of STATIC_CATALOG) byId.set(m.type_id, m)
  for (const m of live) byId.set(m.type_id, m)
  return [...byId.values()]
}
