/**
 * Frontend ModuleInfo fallback when the engine catalog is missing a type
 * (browser demo, or UI ahead of a rebuilt Tauri binary).
 * Live `catalog` invoke wins on merge.
 */

export type PortDesc = { name: string; kind: string; signal: string }
export type ParamDesc = { name: string; min: number; max: number; default: number; unit: string }
export type ModuleInfo = {
  type_id: string
  name: string
  hp: number
  inputs: PortDesc[]
  outputs: PortDesc[]
  params: ParamDesc[]
}

const p = (
  name: string,
  min: number,
  max: number,
  def: number,
  unit = '',
): ParamDesc => ({ name, min, max, default: def, unit })

const inn = (name: string, signal: string): PortDesc => ({
  name,
  kind: 'input',
  signal,
})
const out = (name: string, signal: string): PortDesc => ({
  name,
  kind: 'output',
  signal,
})

